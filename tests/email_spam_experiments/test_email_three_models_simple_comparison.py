# 1. 필요한 도구 불러오기

import pickle
from pathlib import Path

import pandas as pd
import matplotlib.pyplot as plt

from sklearn.metrics import (
    confusion_matrix,
    classification_report,
    ConfusionMatrixDisplay
)

# 2. 파일 경로 설정

BASE_DIR = Path('.')

TEST_PATH = (
    BASE_DIR
    / 'spam_test_master_email_sms_480.csv'
)

MODEL_PATHS = {
    'Logistic Regression': (
        BASE_DIR
        / 'email_spam_logistic_tfidf_v3.pkl'
    ),

    'LinearSVC': (
        BASE_DIR
        / 'email_spam_linearsvc_tfidf_v3.pkl'
    ),

    'MultinomialNB': (
        BASE_DIR
        / 'email_spam_multinomialnb_tfidf_v3.pkl'
    )
}

# 3. 테스트 데이터에서 이메일만 추출

test_data = pd.read_csv(
    TEST_PATH,
    encoding='utf-8-sig'
)

email_test = test_data.loc[
    test_data['channel']
    .astype(str)
    .str.strip()
    == '이메일'
].copy()

X_test = (
    email_test['text']
    .fillna('')
    .astype(str)
)

y_test = (
    email_test['expected_label']
    .astype(int)
)

print('이메일 테스트 데이터:', len(email_test))
print()
print('라벨 분포')
print(y_test.value_counts().sort_index())

# 4. 세 모델의 혼동행렬과 Classification Report 출력

summary_rows = []

for model_name, model_path in MODEL_PATHS.items():

    with open(
        model_path,
        'rb'
    ) as file:
        model = pickle.load(file)

    y_pred = model.predict(
        X_test
    )

    cm = confusion_matrix(
        y_test,
        y_pred,
        labels=[0, 1]
    )

    report_dict = classification_report(
        y_test,
        y_pred,
        labels=[0, 1],
        target_names=['비스팸', '스팸'],
        output_dict=True,
        zero_division=0
    )

    tn, fp, fn, tp = cm.ravel()

    summary_rows.append({
        '모델': model_name,
        'Accuracy': report_dict['accuracy'],
        'Precision': report_dict['스팸']['precision'],
        'Recall': report_dict['스팸']['recall'],
        'F1-score': report_dict['스팸']['f1-score'],
        'TN': int(tn),
        'FP': int(fp),
        'FN': int(fn),
        'TP': int(tp)
    })

    print('=' * 75)
    print('모델:', model_name)
    print()
    print('혼동행렬')
    print(cm)
    print()
    print('Classification Report')
    print(
        classification_report(
            y_test,
            y_pred,
            labels=[0, 1],
            target_names=['비스팸', '스팸'],
            digits=4,
            zero_division=0
        )
    )

    ConfusionMatrixDisplay(
        confusion_matrix=cm,
        display_labels=['Ham', 'Spam']
    ).plot(
        values_format='d'
    )

    plt.title(
        f'{model_name} Confusion Matrix'
    )
    plt.show()

# 5. 핵심 결과 비교표

comparison_result = pd.DataFrame(
    summary_rows
)

comparison_result